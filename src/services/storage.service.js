const fs = require('fs/promises');
const path = require('path');
const crypto = require('crypto');
const sharp = require('sharp');
const env = require('../config/env');
const logger = require('../config/logger');
const ApiError = require('../utils/ApiError');

const MAX_DIMENSION = 1600;

/**
 * Every uploaded photo is re-encoded:
 *  - resized to max 1600px (saves storage + mobile data)
 *  - rotated using EXIF orientation, then ALL metadata is dropped —
 *    phone photos contain GPS coordinates that would reveal where someone lives
 *  - converted to WebP
 */
async function processImage(buffer) {
  try {
    const { data, info } = await sharp(buffer, { failOn: 'error', limitInputPixels: 50_000_000 })
      .rotate()
      .resize({ width: MAX_DIMENSION, height: MAX_DIMENSION, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 80 })
      .toBuffer({ resolveWithObject: true });
    return { data, width: info.width, height: info.height };
  } catch {
    // Wrong extension, corrupted file, or not really an image.
    throw ApiError.badRequest('One of the images could not be read. Please use a JPG, PNG or WEBP photo.');
  }
}

// ---------- Local disk driver ----------
const localDriver = {
  async save(folder, data) {
    const key = `${folder}/${crypto.randomUUID()}.webp`;
    const filePath = path.join(env.storage.uploadDir, key);
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    await fs.writeFile(filePath, data);
    return { key, url: `${env.appUrl}/uploads/${key}` };
  },

  async remove(key) {
    // Keys are generated by us, but guard against path traversal anyway.
    const filePath = path.resolve(env.storage.uploadDir, key);
    if (!filePath.startsWith(path.resolve(env.storage.uploadDir) + path.sep)) return;
    await fs.rm(filePath, { force: true });
  },
};

// ---------- Cloudinary driver ----------
// Free hosting (e.g. Render) wipes the disk on every restart, so photos live in Cloudinary.
// Uses the signed upload REST API directly: no SDK needed.
// https://cloudinary.com/documentation/upload_images#generating_authentication_signatures
function cloudinarySignature(params, apiSecret) {
  const toSign = Object.keys(params)
    .sort()
    .map((k) => `${k}=${params[k]}`)
    .join('&');
  return crypto.createHash('sha1').update(toSign + apiSecret).digest('hex');
}

function cloudinaryDriver(config = env.storage.cloudinary) {
  const { cloudName, apiKey, apiSecret, folder: rootFolder } = config;
  const endpoint = (action) => `https://api.cloudinary.com/v1_1/${cloudName}/image/${action}`;

  async function call(action, params, file) {
    const signed = { ...params, timestamp: Math.floor(Date.now() / 1000) };
    const form = new FormData();
    Object.entries(signed).forEach(([k, v]) => form.append(k, String(v)));
    form.append('api_key', apiKey);
    form.append('signature', cloudinarySignature(signed, apiSecret));
    if (file) form.append('file', new Blob([file], { type: 'image/webp' }), 'photo.webp');

    const res = await fetch(endpoint(action), { method: 'POST', body: form });
    const body = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(`Cloudinary ${action} failed (${res.status}): ${body.error?.message || 'unknown error'}`);
    return body;
  }

  return {
    async save(folder, data) {
      try {
        const body = await call('upload', { folder: `${rootFolder}/${folder}`, public_id: crypto.randomUUID() }, data);
        return { key: body.public_id, url: body.secure_url };
      } catch (err) {
        logger.error(err.message);
        throw new ApiError(502, 'Could not save the photo right now. Please try again.');
      }
    },

    async remove(key) {
      await call('destroy', { public_id: key, invalidate: true });
    },
  };
}

function createDriver(name) {
  if (name === 'local') return localDriver;
  if (name === 'cloudinary') {
    const { cloudName, apiKey, apiSecret } = env.storage.cloudinary;
    if (!cloudName || !apiKey || !apiSecret) {
      throw new Error('STORAGE_DRIVER=cloudinary needs CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY and CLOUDINARY_API_SECRET');
    }
    return cloudinaryDriver();
  }
  throw new Error(`Unknown STORAGE_DRIVER "${name}"`);
}
const driver = createDriver(env.storage.driver);

async function saveImage(folder, buffer) {
  const { data, width, height } = await processImage(buffer);
  const { key, url } = await driver.save(folder, data);
  return { key, url, width, height };
}

// Deleting files must never break the request that triggered it.
async function removeFiles(keys) {
  await Promise.all(
    keys.map((key) =>
      driver.remove(key).catch((err) => logger.warn(`Could not delete file ${key}: ${err.message}`)),
    ),
  );
}

module.exports = { saveImage, removeFiles, cloudinaryDriver, cloudinarySignature };
